#!/bin/sh
# Seeds the consent model (elements + purposes) into a fresh OpenFGC database and
# writes the server-generated purpose IDs to .env.generated, which the MCP server
# loads on top of its own .env.
#
# Idempotent: it looks up each purpose by name before creating it, so a re-run
# reuses the existing IDs rather than creating duplicates. Delete
# .env.generated AND the consent_data volume to start over.
#
# Purpose IDs cannot be pinned -- the server mints them with GenerateUUID() on
# create and CreatePurposeInput has no ID field -- which is exactly why they have
# to be captured here and handed to the MCP server rather than committed.
set -eu

API="${CONSENT_API:-http://consent-server:18040/api/v1}"
ORG="${CONSENT_ORG_ID:-apex}"
GROUP="${CONSENT_GROUP_ID:-apex-banking}"
NS="${CONSENT_ELEMENT_NAMESPACE:-banking}"
OUT="${OUT_FILE:-/out/.env.generated}"

ACCOUNT_PURPOSE=account_information_access
PAYMENT_PURPOSE=payment_initiation

H_JSON='Content-Type: application/json'

echo "==> waiting for the consent server at $API"
i=0
until curl -sf "${API%/api/v1}/health/readiness" >/dev/null 2>&1; do
	i=$((i + 1))
	[ "$i" -gt 60 ] && { echo "!! consent server not ready after 3 minutes"; exit 1; }
	sleep 3
done

# purpose_id NAME -> prints the existing purpose's id, or nothing.
purpose_id() {
	# Listings wrap results in `.data`; `// empty` keeps a miss quiet rather
	# than letting jq exit non-zero and trip `set -e`.
	curl -s -H "org-id: $ORG" -H "group-id: $GROUP" "$API/consent-purposes" |
		jq -r --arg n "$1" '[.data[]? | select(.name == $n)] | .[0].purposeId // empty'
}

echo "==> creating consent elements (namespace: $NS)"
curl -s -o /dev/null -X POST "$API/consent-elements" \
	-H "org-id: $ORG" -H "group-id: $GROUP" -H "$H_JSON" \
	-d "[{\"name\":\"ReadAccountsDetail\",\"namespace\":\"$NS\",\"type\":\"basic\",\"displayName\":\"View account details\",\"description\":\"View account details\"},
	     {\"name\":\"ReadBalances\",\"namespace\":\"$NS\",\"type\":\"basic\",\"displayName\":\"View balances\",\"description\":\"View balances\"},
	     {\"name\":\"ReadTransactionsDetail\",\"namespace\":\"$NS\",\"type\":\"basic\",\"displayName\":\"View transaction history\",\"description\":\"View transaction history\"},
	     {\"name\":\"InitiatePayment\",\"namespace\":\"$NS\",\"type\":\"basic\",\"displayName\":\"Make this payment\",\"description\":\"Make this payment\"}]" || true

# Read elements are optional so the customer can approve them individually;
# the payment element is mandatory -- a payment consent with it unapproved is
# meaningless.
account_id="$(purpose_id "$ACCOUNT_PURPOSE")"
if [ -z "$account_id" ]; then
	echo "==> creating purpose $ACCOUNT_PURPOSE"
	account_id="$(curl -s -X POST "$API/consent-purposes" \
		-H "org-id: $ORG" -H "group-id: $GROUP" -H "$H_JSON" \
		-d "{\"name\":\"$ACCOUNT_PURPOSE\",\"displayName\":\"Account information access\",
		     \"description\":\"Allow the AI assistant to read your account information\",
		     \"elements\":[{\"name\":\"ReadAccountsDetail\",\"namespace\":\"$NS\",\"version\":\"v1\",\"mandatory\":false},
		                  {\"name\":\"ReadBalances\",\"namespace\":\"$NS\",\"version\":\"v1\",\"mandatory\":false},
		                  {\"name\":\"ReadTransactionsDetail\",\"namespace\":\"$NS\",\"version\":\"v1\",\"mandatory\":false}]}" |
		jq -r '.purposeId // empty')"
else
	echo "==> reusing purpose $ACCOUNT_PURPOSE ($account_id)"
fi

payment_id="$(purpose_id "$PAYMENT_PURPOSE")"
if [ -z "$payment_id" ]; then
	echo "==> creating purpose $PAYMENT_PURPOSE"
	payment_id="$(curl -s -X POST "$API/consent-purposes" \
		-H "org-id: $ORG" -H "group-id: $GROUP" -H "$H_JSON" \
		-d "{\"name\":\"$PAYMENT_PURPOSE\",\"displayName\":\"Payment initiation\",
		     \"description\":\"Authorise a single payment\",
		     \"elements\":[{\"name\":\"InitiatePayment\",\"namespace\":\"$NS\",\"version\":\"v1\",\"mandatory\":true}]}" |
		jq -r '.purposeId // empty')"
else
	echo "==> reusing purpose $PAYMENT_PURPOSE ($payment_id)"
fi

[ -n "$account_id" ] && [ -n "$payment_id" ] || {
	echo "!! could not resolve both purpose ids (account='$account_id' payment='$payment_id')"
	exit 1
}

# Written atomically, merging with whatever thunder-init and amp-init wrote -- a half-written
# file would otherwise look complete to the next run and to every env_file.
tmp="$OUT.consent.tmp"
if [ -f "$OUT" ]; then
	grep -v '^MCP_CONSENT__\|^# CONSENT_COMPLETE' "$OUT" > "$tmp" || true
fi
cat >> "$tmp" <<EOF
# Generated by init/consent-init.sh -- purpose IDs are minted by the consent
# server (GenerateUUID on create), so they differ per environment.
MCP_CONSENT__ORG_ID=$ORG
MCP_CONSENT__GROUP_ID=$GROUP
MCP_CONSENT__ELEMENT_NAMESPACE=$NS
MCP_CONSENT__ACCOUNT_ACCESS_PURPOSE_ID=$account_id
MCP_CONSENT__ACCOUNT_ACCESS_PURPOSE_NAME=$ACCOUNT_PURPOSE
MCP_CONSENT__PAYMENT_PURPOSE_ID=$payment_id
MCP_CONSENT__PAYMENT_PURPOSE_NAME=$PAYMENT_PURPOSE
# CONSENT_COMPLETE
EOF
mv "$tmp" "$OUT"

echo "==> consent model seeded; purpose ids written to $OUT"
